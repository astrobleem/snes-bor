#!/usr/bin/env python3
"""Parse tad-compiler ca65-export output and emit LoROM Poppy blob-symbol equates."""
import re
from pathlib import Path


def main():
    out = Path(__file__).resolve().parents[1] / "build"
    s = (out / "audio-data.s").read_text()
    loader = int(re.search(r"Tad_Loader_SIZE\s*=\s*(\d+)", s).group(1))
    driver = int(re.search(r"Tad_AudioDriver_SIZE\s*=\s*(\d+)", s).group(1))
    driver_off = int(re.search(r"Tad_AudioDriver_Bin\s*:=\s*__Tad_AudioData_0\s*\+\s*(\d+)", s).group(1))
    table_off = int(re.search(r"Tad_DataTable\s*:=\s*__Tad_AudioData_0\s*\+\s*(\d+)", s).group(1))
    n_items = int(re.search(r"N_DATA_ITEMS\s*=\s*(\d+)", s).group(1))
    # __Tad_AudioData_0's real address (blob start), Poppy-side. Historically
    # $00B02B -- mid-bank-0, because the project believed Poppy's `.bank N`
    # (N != 0) handling was broken. That belief was wrong (fixed in the fork,
    # re-measured 2026-08-19); the blob has been relocated to a real bank
    # boundary: `.bank 1`, `.org $8000`, with a 51-byte pad (matching this
    # file's own `.assert .sizeof(LoadAudioData) = 51` -- the real ca65
    # LoadAudioData proc that upstream places immediately before the blob in
    # the same AUDIO0 segment; this project's LoadAudioData is a separate
    # routine elsewhere, so the pad here is filler, not real code) ahead of
    # __Tad_AudioData_0 itself. If the blob moves again, update this to match
    # main.pasm's `.bank 1` region and re-run this script.
    base = 0x018000 + 0x33

    (out / "tad_blob_syms.pasm").write_text(
        "; GENERATED by tad-compiler ca65-export; do not edit.\n"
        f"AUDIO_DATA_BANK = ${(base >> 16) & 0xFF:02X}\n"
        f"Tad_Loader_Bin = ${base:06X}\n"
        f"Tad_Loader_SIZE = {loader}\n"
        f"Tad_AudioDriver_Bin = ${base + driver_off:06X}\n"
        f"Tad_AudioDriver_SIZE = {driver}\n"
        f"Tad_DataTable = ${base + table_off:06X}\n"
        f"N_DATA_ITEMS = {n_items}\n"
    )
    print(f"generated {out / 'tad_blob_syms.pasm'}")


if __name__ == "__main__":
    main()