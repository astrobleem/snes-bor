#!/usr/bin/env python3
"""Parse tad-compiler ca65-export output and emit LoROM Poppy blob-symbol equates."""
import re
from pathlib import Path


def main():
    out = Path(__file__).resolve().parents[1] / "build"
    s = (out / "audio-data.s").read_text()
    loader = int(re.search(r"Tad_Loader_SIZE\s*=\s*(\d+)", s).group(1))
    driver = int(re.search(r"Tad_AudioDriver_SIZE\s*=\s*(\d+)", s).group(1))
    driver_off = int(re.search(r"Tad_AudioDriver_Bin\s*:=\s*__Tad_AudioData_0\s*\+\s*(\d+)", s).group(1))
    table_off = int(re.search(r"Tad_DataTable\s*:=\s*__Tad_AudioData_0\s*\+\s*(\d+)", s).group(1))
    n_items = int(re.search(r"N_DATA_ITEMS\s*=\s*(\d+)", s).group(1))
    base = 0x00B000 + 0x2B

    (out / "tad_blob_syms.pasm").write_text(
        "; GENERATED by tad-compiler ca65-export; do not edit.\n"
        f"AUDIO_DATA_BANK = $00\n"
        f"Tad_Loader_Bin = ${base:06X}\n"
        f"Tad_Loader_SIZE = {loader}\n"
        f"Tad_AudioDriver_Bin = ${base + driver_off:06X}\n"
        f"Tad_AudioDriver_SIZE = {driver}\n"
        f"Tad_DataTable = ${base + table_off:06X}\n"
        f"N_DATA_ITEMS = {n_items}\n"
    )
    print(f"generated {out / 'tad_blob_syms.pasm'}")


if __name__ == "__main__":
    main()