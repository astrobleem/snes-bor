"""Single queue ABI and build-scoped WRAM/link contract; no game identity rules."""
import json
import re
import struct
from pathlib import Path

SPEC=json.loads(Path(__file__).with_suffix('.json').read_text())
for name in ('arena_base','arena_end_exclusive'): SPEC[name]=int(SPEC[name],0)
RECORD_SIZE=SPEC['record_size']
COUNT_MAX=min((1<<SPEC['runtime_count_bits'])-1,(1<<SPEC['runtime_index_bits'])-1)
ARENA_BYTES=SPEC['arena_end_exclusive']-SPEC['arena_base']
TARGET_CAPACITY=min(COUNT_MAX,(ARENA_BYTES-SPEC['guard_bytes']-SPEC['fault_bytes'])//RECORD_SIZE)
if (SPEC['version']!=1 or RECORD_SIZE!=struct.calcsize('<HHBBBBBB') or SPEC['runtime_count_bits']!=8
        or SPEC['runtime_index_bits']!=8 or SPEC['catalog_count_bits']!=16 or SPEC['copy_count_bits']!=16):
    raise ValueError('queue ABI version requires a matching runtime encoder/iterator implementation')


class QueueCapacityError(ValueError):
    def __init__(self,diagnostic):
        self.diagnostic=diagnostic
        super().__init__(json.dumps(diagnostic,sort_keys=True))


def check_count(count, *, capacity=TARGET_CAPACITY, project, set_name, stage, source_path):
    if not isinstance(count,int) or not 0<=count<=min(capacity,TARGET_CAPACITY):
        raise QueueCapacityError(dict(code='QUEUE_CAPACITY_EXCEEDED',project=project,set=set_name,
            stage=stage,source_path=source_path,packed_records=count,runtime_capacity=capacity,
            required_bytes=count*RECORD_SIZE if isinstance(count,int) else None,available_bytes=capacity*RECORD_SIZE,
            target_limit=TARGET_CAPACITY,arena_bytes=ARENA_BYTES,count_bits=SPEC['runtime_count_bits']))
    return count*RECORD_SIZE


def packed_count(blob, **context):
    if len(blob)%RECORD_SIZE:
        raise ValueError(dict(code='QUEUE_RECORD_SIZE_MISMATCH',bytes=len(blob),record_size=RECORD_SIZE,**context))
    count=len(blob)//RECORD_SIZE
    check_count(count,**context)
    return count


def plan_build(rows):
    rows=list(rows)
    for row in rows:
        check_count(row['packed_records'],project=row['project'],set_name=row['set'],
                    stage=row['stage'],source_path=row['source_path'])
    capacity=max((r['packed_records'] for r in rows),default=0)
    return dict(version=SPEC['version'],record_size=RECORD_SIZE,capacity=capacity,
        buffer_base=SPEC['arena_base'],buffer_bytes=capacity*RECORD_SIZE,
        buffer_end_exclusive=SPEC['arena_base']+capacity*RECORD_SIZE,
        target_capacity=TARGET_CAPACITY,arena_end_exclusive=SPEC['arena_end_exclusive'],
        error_address=SPEC['arena_end_exclusive']-1,guard_bytes=SPEC['guard_bytes'],
        runtime_count_bits=SPEC['runtime_count_bits'],runtime_index_bits=SPEC['runtime_index_bits'],
        copy_count_bits=SPEC['copy_count_bits'],catalog_count_bits=SPEC['catalog_count_bits'],
        stages=rows)


def source_set_names(text):
    """Diagnostic labels only; not a progression parser or capability waiver."""
    result={};current='standalone'
    for line in text.splitlines():
        parts=line.split('#',1)[0].split()
        if len(parts)==2 and parts[0].casefold()=='set': current=parts[1]
        elif len(parts)==2 and parts[0].casefold()=='file':
            result[parts[1].replace('\\','/').casefold()]=current
    return result


def write_contract(plan, output):
    if plan!=plan_build(plan['stages']):
        raise ValueError('queue contract is not derived from the finalized stage rows')
    output=Path(output);output.parent.mkdir(parents=True,exist_ok=True)
    output.with_suffix('.json').write_text(json.dumps(plan,indent=2,sort_keys=True)+'\n')
    constants=dict(QUEUE_ABI_VERSION=plan['version'],QUEUE_RECORD_SIZE=plan['record_size'],
        QUEUE_CAPACITY=plan['capacity'],QUEUE_BUFFER_BYTES=plan['buffer_bytes'],
        QUEUE_COUNT_BITS=plan['runtime_count_bits'],QUEUE_INDEX_BITS=plan['runtime_index_bits'],
        QUEUE_COPY_COUNT_BITS=plan['copy_count_bits'],QUEUE_COUNT_CEILING=plan['capacity']+1,
        QUEUE_BUFFER_BASE=plan['buffer_base'],QUEUE_BUFFER_END=plan['buffer_end_exclusive'],
        QUEUE_ERROR=plan['error_address'])
    lines=['; Generated by build_rom.py from tools/queue_abi.json and finalized linked queues.']
    lines += [f'{k} = {v}' for k,v in constants.items()]
    output.with_suffix('.pasm').write_text('\n'.join(lines)+'\n')


def assert_layout(root,plan):
    """Check the real include closure plus the adjacent indexed-buffer extents."""
    root=Path(root).resolve();texts={}
    def visit(path):
        path=path.resolve()
        if path in texts: return
        text=path.read_text();texts[path]=text
        for line in text.splitlines():
            match=re.match(r'\s*\.include\s+"([^"]+)"',line.split(';',1)[0])
            if match: visit(path.parent/match[1])
    visit(root/'src/main.pasm')
    equates={}
    for path,text in texts.items():
        for line in text.splitlines():
            code=line.split(';',1)[0]
            m=re.match(r'\s*(\w+)\s*=\s*(\$[0-9a-fA-F]+|\d+)\s*$',code)
            if m: equates[m[1]]=int(m[2][1:],16) if m[2].startswith('$') else int(m[2])
            if path==root/'src/generated/queue_abi.pasm': continue
            for literal in re.findall(r'\$([0-9a-fA-F]{6})\b',code):
                if SPEC['arena_base']<=int(literal,16)<SPEC['arena_end_exclusive']:
                    raise ValueError(f'QUEUE_WRAM_OVERLAP: {path}: {code}')
    previous=max(equates['StreamScroll_TileBufN']+32*equates['STREAM_SCROLL_BUDGET_MAX'],
                 equates['StreamScrollFp_TileBufN']+16*equates['STREAM_SCROLLFP_BUDGET_MAX'])
    following=equates['StreamCacheFp_Tile2Slot']
    if not previous<=plan['buffer_base']<=plan['buffer_end_exclusive']+SPEC['guard_bytes']<following:
        raise ValueError('QUEUE_WRAM_OVERLAP: indexed stream buffers or frontpanel table')
    if plan['buffer_end_exclusive']>plan['error_address']:
        raise ValueError('QUEUE_WRAM_OVERLAP: fault cell')
    return dict(previous_end_exclusive=previous,arena_base=SPEC['arena_base'],arena_bytes=ARENA_BYTES,
                following_base=following,buffer_end_exclusive=plan['buffer_end_exclusive'],
                include_files=len(texts),status='PASS')
