"""Link HUD model names in runtime roster order, without changing identity.

BOR.C zeroes the model and applies its `name` directive; spawn() copies that
name, and a nonempty instance alias overrides it. MODELS.TXT registration or
directory spelling is not a substitute display name. Bytes are Latin-1,
bounded by BOR's MAX_NAME_LEN=20; emit numeric bytes, never assembler strings.
"""
from pathlib import Path
import argparse
import sys

from compiler import ROOT, Source, key, parse_entity
from environment_semantics import SOURCE_NAME_BYTES


def family_sources(stage_configs, root=ROOT):
    result = {}
    for config in stage_configs:
        family, path = config['family'], Path(root) / config['pak']
        if family in result and result[family] != path:
            raise ValueError(f'HUD_NAME_AMBIGUOUS_SOURCE: {family}')
        result[family] = path
    return result


def render(roster_configs, sources):
    """Return PASM and provenance rows; sources maps family to Source/path.

    A config may explicitly supply pak/source_definition. Otherwise resolve
    source_character against registered model files (exact file stem or
    containing directory). Missing/ambiguous identities fail before output.
    """
    if not 1 <= len(roster_configs) <= 256:
        raise ValueError('HUD_NAME_ROSTER_CAPACITY: expected 1..256 byte identities')
    catalogs = {}
    rows = []
    for runtime_id, config in enumerate(roster_configs):
        origin = config.get('pak') or sources.get(config['family'])
        if origin is None:
            raise ValueError(f'HUD_NAME_SOURCE_MISSING: {config["family"]}')
        if not isinstance(origin, Source):
            origin = Path(origin)
            if not origin.is_absolute():
                origin = ROOT / origin
        cache_key = origin if isinstance(origin, Source) else str(origin)
        if cache_key not in catalogs:
            source = origin if isinstance(origin, Source) else Source(origin)
            # The name linker consumes only registrations; foreign MODELS
            # options (e.g. nocost) belong to that dialect's gameplay loader.
            models = {}
            for directive in source.lines('DATA/MODELS.TXT'):
                if directive.name not in ('load', 'know'):
                    continue
                if len(directive.values) != 2:
                    raise ValueError('HUD_NAME_REGISTRATION: expected model and path')
                path = source.resolve(directive.values[1])
                models[key(path)] = dict(source_path=path,
                    entity=parse_entity(source.read(path).decode('latin1')))
            catalogs[cache_key] = models
        catalog = catalogs[cache_key]
        if config.get('source_definition'):
            wanted = key(config['source_definition'])
            matches = [m for m in catalog.values() if key(m['source_path']) == wanted]
        else:
            wanted = key(config['source_character']).removesuffix('.txt')
            matches = [m for m in catalog.values()
                       if key(m['source_path']).removesuffix('.txt') == wanted
                       or key(m['source_path']).rsplit('/', 1)[0] == wanted]
        if len(matches) != 1:
            raise ValueError(f'HUD_NAME_IDENTITY: runtime {runtime_id}: {wanted}: {len(matches)} matches')
        model = matches[0]
        name = (model['entity']['name'] or '').encode('latin1')[:SOURCE_NAME_BYTES]
        if b'\0' in name:
            raise ValueError(f'HUD_NAME_EMBEDDED_NUL: {wanted}')
        rows.append(dict(runtime_id=runtime_id, source_path=model['source_path'],
                         display_name=name.decode('latin1')))
    lines = ['; Generated by tools/bor_compile/generate_hud_names.py; do not edit.',
             '; Runtime roster indices are preserved; names never select actor behavior.',
             f'HudOpponent_ModelCount = {len(rows)}', 'HudOpponent_ModelPtrs:']
    lines.extend(f'    .dw HudOpponent_Name{r["runtime_id"]}' for r in rows)
    lines += ['HudOpponent_Unknown:', '    .db 63,0']
    for row in rows:
        lines += [f'HudOpponent_Name{row["runtime_id"]}:',
                  '    .db ' + ','.join(map(str, row['display_name'].encode('latin1') + b'\0'))]
    lines += ['HudOpponent_ModelNamesEnd:', '']
    return '\n'.join(lines), rows


def generate(roster_configs, sources, output):
    text, rows = render(roster_configs, sources)
    Path(output).write_text(text, encoding='ascii')
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/generated/hud_opponent_names.pasm')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT / 'tools/audio'))
    from shipped_content import ROSTER_CONFIGS, STAGE_CONFIGS
    text, rows = render(ROSTER_CONFIGS, family_sources(STAGE_CONFIGS))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding='ascii') != text:
            raise SystemExit('HUD_NAME_GENERATED_STALE: ' + str(args.output))
    else:
        args.output.write_text(text, encoding='ascii')
    print(f'HUD model names: {len(rows)} source bindings verified')


if __name__ == '__main__':
    main()
