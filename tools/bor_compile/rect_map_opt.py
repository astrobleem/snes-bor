def transform(lines: Sequence[str]) -> list[str]:
    """Source-text splice after direct_pair_dma.transform; fail closed on drift.

    Places routines in the current $D000 routines segment *before* existing
    WarmMapDmaHigh/Low, and replaces only the final committed-map copy.
    Whole bank/symbol audit by Sol must reject any collision with $D400 direct
    DMA or $E000 row kernel and verify existing code/data identities.
    """
    a=list(lines)
    anchors=('WarmSparseMaps:','WarmMapDmaHigh:', 'OnlineMapsTransfer:',
             'OnlineComplete:', 'WarmCommitMapRect:','.org $D400',
             '.org $E000','OnlineBlank:','WarmDirectPair:','WarmMapDmaLow:')
    if any(a.count(x)!=1 for x in anchors if x!='WarmCommitMapRect:'):
        raise MapContractError('RECT_MAP_EXPECTED_LABELS_MISSING_OR_DUPLICATED')
    if a.count('WarmCommitMapRect:'):
        raise MapContractError('RECT_MAP_ALREADY_PATCHED')
    if not (a.index('OnlineBlank:')<a.index('OnlineMapsTransfer:')<a.index('OnlineComplete:')):
        raise MapContractError('RECT_MAP_PUBLICATION_ORDER_DRIFT')
    if not (a.index('WarmSparseMaps:')<a.index('WarmMapDmaHigh:')<a.index('.org $D400')):
        raise MapContractError('RECT_MAP_ROUTINE_ORDER_DRIFT')
    scan_at=a.index('WarmSparseMaps:');scan_end=a.index('WarmMapDmaHigh:',scan_at)
    # The retained Poppy emitter spells these two immutable long addresses in
    # decimal; accept only the equivalent spelling, not different operands.
    normalized=[s.replace('4374528,x','$42C000,x').replace('4376576,x','$42C800,x') for s in a[scan_at:scan_end]]
    if normalized!=ORIGINAL_SCAN:
        raise MapContractError('RECT_MAP_SOURCE_SCAN_DRIFT')
    commit_at=a.index('OnlineMapsTransfer:')
    if a[commit_at:commit_at+len(ORIGINAL_COMMIT)]!=ORIGINAL_COMMIT:
        raise MapContractError('RECT_MAP_COMMIT_FENCE_DRIFT')
    # Patch later-addressed block first, to avoid index invalidation.
    a[scan_at:scan_end]=SCAN_REPLACEMENT+COMMIT_ROUTINE
    commit_at=a.index('OnlineMapsTransfer:')
    a[commit_at:commit_at+len(ORIGINAL_COMMIT)]=[
        'OnlineMapsTransfer:','.a16','.i16',' jsr WarmFlush',
        ' jsr WarmCommitMapRect',
    ]
    return a


def _check(base: Sequence[int], pending: Sequence[int], rect: tuple[int,int,int,int]) -> tuple[int,int,int,int]:
    if len(base)!=1024 or len(pending)!=1024:
        raise ValueError('MAP_32_BY_32_WORD_DOMAIN')
    x0,x1,y0,y1=rect
    if not (0<=x0<=x1<32 and 0<=y0<=y1<28):
        raise ValueError('MAP_UNION_BOUNDS')
    if any(not 0<=v<=65535 for v in base) or any(not 0<=v<=65535 for v in pending):
        raise ValueError('MAP_WORD_DOMAIN')
    return x0,x1,y0,y1


def rect_runs(base:Sequence[int], pending:Sequence[int], rect:tuple[int,int,int,int]) -> list[tuple[int,int]]:
    """Model native scan: byte offset and length per changed contiguous row run."""
    x0,x1,y0,y1=_check(base,pending,rect)
    out=[]
    for y in range(y0,y1+1):
        x=x0
        while x<=x1:
            if base[y*32+x]==pending[y*32+x]:
                x+=1;continue
            begin=x
            while x<=x1 and base[y*32+x]!=pending[y*32+x]:x+=1
            out.append((2*(y*32+begin),2*(x-begin)))
    return out


def full_runs(base:Sequence[int], pending:Sequence[int]) -> list[tuple[int,int]]:
    if len(base)!=1024 or len(pending)!=1024:raise ValueError('MAP_DOMAIN')
    out=[];start=None
    for i in range(1025):
        changed=i<1024 and base[i]!=pending[i]
        if changed and start is None:start=i
        if not changed and start is not None:
            out.append((2*start,2*(i-start)));start=None
    return out


def apply_word_runs(base:Sequence[int], pending:Sequence[int],runs:Sequence[tuple[int,int]])->list[int]:
    result=list(base)
    for offset,size in runs:
        if offset%2 or size%2 or not 0<=offset<=2048 or not 0<size<=2048-offset:
            raise ValueError('MAP_TRANSFER_DOMAIN')
        result[offset//2:(offset+size)//2]=pending[offset//2:(offset+size)//2]
    return result


def rect_commit(base:Sequence[int],pending:Sequence[int],rect:tuple[int,int,int,int])->list[int]:
    x0,x1,y0,y1=_check(base,pending,rect)
    out=list(base)
    for y in range(y0,y1+1):
        start=y*32+x0;end=y*32+x1+1
        out[start:end]=pending[start:end]
    return out
