"""Resolve immutable source pass dispatch at build time, never by model name.

Live existence/error and parity remain at every callback boundary. Immutable
tick time/world identity are installed on the first enabled pass. Callbacks
must preserve those inputs; an in-pass birth must initialize them at bind.
"""
PASSES = ('S6_WorldLost', 'S6_WorldGravity', 'S6_ThinkPass',
          'S6_AnimationPass', 'S6_WorldAttack', 'S6_WorldHealth')


def emit_layout(contexts):
    """Immutable linker slot layout only; every mutable boundary remains live.

    Requires the host's existing acquisition lease over the identical table.
    D stays world except inside each callback; callback restores D/DBR/M/X.
    """
    contexts = tuple(contexts)
    assert contexts and len(set(contexts)) == len(contexts)
    assert all(0 < c < 0x1f00 and c % 256 == 0 for c in contexts)
    out = ['; Generated fixed layout traversal, not model or replay specialization.']
    for p, callback in enumerate(PASSES):
        label = f'S6_Layout_P{p}'
        end = f'{label}_end'
        out += [label+':', '    lda #'+str(p), '    sta $38', '    stz $36']
        if p < 2:
            out += ['    lda $40', f'    bne {label}_enabled', f'    jmp {end}', label+'_enabled:']
        for i, ctx in enumerate(contexts):
            visit = f'{label}_S{i}'
            nxt = f'{visit}_next'
            out += [visit+':', f'    lda #{i}', '    sta $36']
            if p == 4:
                out += ['    eor $3C', '    and #1', f'    bne {nxt}']
            out += [f'    lda.l ${0x7e0000+ctx+0xf6:06X}', f'    beq {nxt}',
                    f'    lda.l ${0x7e0000+ctx+0xfc:06X}', f'    beq {visit}_call',
                    '    sta $3A', '    rtl', visit+'_call:']
            if p == 2:
                out += ['    lda $40', f'    bne {visit}_ready']
            if p in (0, 2):
                for src, dst in ((0x3c,0xd0),(0x3e,0xd2),(0x42,0x36)):
                    out += [f'    lda ${src:02X}', f'    sta.l ${0x7e0000+ctx+dst:06X}']
            out += [visit+'_ready:', '    phd', f'    lda #${ctx:04X}', '    tcd',
                    f'    jsl {callback}', '    lda $FC', '    pld', '    cmp #0',
                    f'    beq {nxt}', '    sta $3A', '    rtl', nxt+':']
        out += [f'    lda #{len(contexts)}', '    sta $36', end+':']
    out += ['    jmp S6_UpdateWorld__done']
    return '\n'.join(line+'\n    .a16\n    .i16' if line.endswith(':') else line for line in out)+'\n'


def emit():
    lines = ['; Generated by tools/bor_compile/world_pass_codegen.py; no actor data.']
    for p, callback in enumerate(PASSES):
        label = f'S6_UpdateWorld_P{p}'
        next_pass = f'S6_UpdateWorld_P{p+1}' if p < 5 else 'S6_UpdateWorld__done'
        lines += [f'{label}:', '    .a16', '    .i16',
                  f'    lda #{p}', '    sta $38', '    stz $36']
        if p < 2:
            lines += ['    lda $40', f'    bne {label}__slot', f'    jmp {next_pass}']
        lines += [f'{label}__slot:', '    lda $36', '    cmp $34',
                  f'    bcc {label}__visit', f'    jmp {next_pass}', f'{label}__visit:']
        if p == 4:
            lines += ['    lda $36', '    eor $3C', '    and #1', f'    bne {label}__next']
        lines += ['    lda $36', '    asl a', '    tay', '    lda [$30],y',
                  f'    beq {label}__next', '    tax', '    lda.l $7E00F6,x',
                  f'    beq {label}__next', '    lda.l $7E00FC,x',
                  f'    beq {label}__call', '    sta $3A', '    rtl', f'{label}__call:']
        if p==2:
            lines += ['    lda $40', f'    bne {label}__time_ready']
        if p in (0,2):
            lines += ['    lda $3C', '    sta.l $7E00D0,x', '    lda $3E',
                      '    sta.l $7E00D2,x', '    lda $42', '    sta.l $7E0036,x']
        if p==2:
            lines += [f'{label}__time_ready:']
        lines += ['    phd', '    txa', '    tcd', f'    jsl {callback}',
                  '    lda $FC', '    pld', '    cmp #0', f'    beq {label}__next',
                  '    sta $3A', '    rtl', f'{label}__next:', '    inc $36',
                  f'    jmp {label}__slot']
    lines += ['    ; Final public iterator state matches the reference traversal.']
    # Poppy's width audit requires an explicit contract at each branch target.
    annotated=[]
    for i,line in enumerate(lines):
        annotated.append(line)
        if line.endswith(':') and (i+1==len(lines) or lines[i+1]!='    .a16'):
            annotated.extend(('    .a16', '    .i16'))
    return '\n'.join(annotated) + '\n'


if __name__ == '__main__':
    import sys
    from pathlib import Path
    if '--check' in sys.argv:
        path=Path(__file__).resolve().parents[2]/'src/core/actor_source_world.pasm'
        text=path.read_text()
        actual=text.split('S6_UpdateWorld__start:\n',1)[1].split('S6_UpdateWorld__done:',1)[0]
        assert actual==emit(), 'SOURCE_WORLD_GENERATED_DISPATCH_STALE'
        print('PASS_GENERATED_WORLD_DISPATCH')
    else:
        print(emit(), end='')
