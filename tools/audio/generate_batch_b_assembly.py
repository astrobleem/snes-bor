#!/usr/bin/env python3
"""Generate the generic Batch-B stream source and frame/diesound tables."""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "tools/audio/batch_b_audio.json"
BUDGET = ROOT / "assets/audio/batch_b_budget.json"
STREAM_OUT = ROOT / "src/audio_batch_b_stream_sources.pasm"
TABLE_OUT = ROOT / "src/core/vm/audio_batch_b_generated.pasm"

SEMANTICS = {
    "NONE": "$FF", "DIE1": "$01", "FOOTDIE": "$02", "ROCKDIE": "$03",
    "RHINODIE": "$04", "BEBOPDIE": "$05", "TURTLEDIE": "$06",
    "FALL": "$07", "JUMP": "$08", "GET": "$09", "MONEY": "$0A",
    "PUNCH": "$0B", "ONEUP": "$0C", "BEEP": "$0D", "BEEP2": "$0E",
    "PAUSE": "$0F", "METAL": "$10", "SPIN": "$11", "DASH": "$12",
    "PUNCH0": "$13", "THROW": "$14", "GUNSHOT": "$15", "WAVE": "$16",
    "BOAR": "$17", "PIZZA1": "$18", "RHINO": "$19", "KLUNK": "$1A",
    "WOOD": "$1B", "DIE2": "$1C",
}

RESIDENT_IDS = {"SPIN": 9, "DASH": 10, "METAL": 11}


def source_key(value: str) -> str:
    return value.upper().replace("/", "\\")


def source_name(value: str) -> str:
    return Path(value.replace("\\", "/")).stem.lower().replace("~", "")


def main() -> None:
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    budget = json.loads(BUDGET.read_text(encoding="utf-8"))
    budget_rows = budget.get("resident", []) + budget.get("stream", [])
    budget_by_asset = {source_key(row["asset"]): row for row in budget_rows}
    source_ids = {source_key(asset): index for index, asset in enumerate(config["stream"], 1)}
    source_rows = [{"asset": "tmnt:DATA\\SOUNDS\\FOOTDIE.WAV", "source_id": 0,
                    "length": (ROOT / "assets/audio/footdie.brr").stat().st_size,
                    "brr": "assets/audio/footdie.brr"}]
    for asset in config["stream"]:
        row = budget_by_asset[source_key(asset)]
        source_rows.append({"asset": asset, "source_id": source_ids[source_key(asset)],
                            "length": row["brr_bytes"], "brr": row["stream_brr_path"]})

    stream_lines = [
        "; GENERATED by tools/audio/generate_batch_b_assembly.py; do not edit.",
        "; One physical source occupies one ROM bank so the existing stream",
        "; producer can address every source with a 16-bit source offset.",
    ]
    for bank, row in enumerate(source_rows[1:], 13):
        label = f"AudioStream_Source_{row['source_id']}"
        stream_lines += [f".bank {bank}", ".org $8000", f"{label}:",
                         f"    .incbin \"../{row['brr']}\""]
    STREAM_OUT.write_text("\n".join(stream_lines) + "\n", encoding="utf-8")

    die_semantics = []
    die_sources = []
    pain_semantics = ["$FF"] * 21
    pain_sources = ["$FF"] * 21
    for index in range(21):
        row = config["diesounds"].get(str(index), {"semantic": "NONE"})
        die_semantics.append(SEMANTICS[row["semantic"]])
        die_sources.append("$FF" if "source" not in row else str(row["source"]))
    for row in config.get("pain_sounds", []):
        roster = row["roster"]
        pain_semantics[roster] = SEMANTICS[row["semantic"]]
        pain_sources[roster] = str(source_ids[source_key(row["source"])])

    records = []
    for row in config["frame_sounds"]:
        arg = RESIDENT_IDS[row["semantic"]] if row["backend"] == "resident" else source_ids[source_key(row["source"])]
        for variant in row.get("variants", [None]):
            for jump_mode in row.get("jump_modes", [None]):
                for frame in row["frames"]:
                    records.append([
                        row["roster"], row["selected"],
                        "$FF" if variant is None else variant,
                        "$FF" if jump_mode is None else jump_mode,
                        frame, 0 if row["backend"] == "resident" else 1,
                        arg, SEMANTICS[row["semantic"]],
                    ])

    lines = [
        "; GENERATED by tools/audio/generate_batch_b_assembly.py; do not edit.",
        "; Shared Batch-B source lengths/chunks, diesound map, and authored",
        "; frame-sound records. A record is roster/selected/variant/jump-mode,",
        "; frame/backend/argument/semantic, eight bytes total.",
        "AUDIO_STREAM_SOURCE_COUNT = %d" % len(source_rows),
        "AUDIO_STREAM_SOURCE_NONE = $FF",
        "AudioStream_SourceLengthTable:",
        "    .dw " + ", ".join(str(row["length"]) for row in source_rows),
        "AudioStream_SourceChunkTable:",
        "    .dw " + ", ".join(str(math.ceil(row["length"] / 144)) for row in source_rows),
        "AudioSemantic_DiesoundByRoster:",
        "    .db " + ", ".join(die_semantics),
        "AudioSemantic_DiesoundSourceByRoster:",
        "    .db " + ", ".join(die_sources),
        "AudioSemantic_PainByRoster:",
        "    .db " + ", ".join(pain_semantics),
        "AudioSemantic_PainSourceByRoster:",
        "    .db " + ", ".join(pain_sources),
        "AUDIO_FRAME_SOUND_RECORD_SIZE = 8",
        "AUDIO_FRAME_SOUND_RECORD_COUNT = %d" % len(records),
        "Audio_FrameSoundRecords:",
    ]
    for record in records:
        lines.append("    .db " + ", ".join(str(value) for value in record))
    TABLE_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {STREAM_OUT} ({len(source_rows)} sources)")
    print(f"wrote {TABLE_OUT} ({len(records)} frame records)")


if __name__ == "__main__":
    main()
