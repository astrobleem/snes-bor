"""Generate source-backed new Normal bindings; retain pinned S7 adapters."""
from __future__ import annotations

import json
from pathlib import Path

from s8_audio_scope import ROOT, baseline, roster, normal_scope

OUTPUT = ROOT / "src/core/normal_audio_generated.pasm"


def bindings() -> dict:
    from shipped_content import ROSTER_CONFIGS
    from plan_action_residency import source_entry
    from pak_extract import extract
    from entity_parse import parse_entity
    from generate_batch_b_assembly import SEMANTICS
    if len(ROSTER_CONFIGS) > 255:
        raise SystemExit("FAIL: Normal audio roster count exceeds byte dispatch ABI")
    old = roster()
    spec = json.loads(baseline("tools/audio/batch_b_audio.json"))
    known_streams = {a: i for i, a in enumerate(spec["stream"], 1)}
    known_semantics = {}
    for row in spec["diesounds"].values():
        if row.get("source", 0) > 0:
            known_semantics[row["source"]] = int(SEMANTICS[row["semantic"]][1:], 16)
    rows = []
    normal = normal_scope()
    for i, cfg in enumerate(ROSTER_CONFIGS):
        legacy = spec["diesounds"].get(str(i), {}) if i < 21 else {}
        semantic = int(SEMANTICS[legacy.get("semantic", "NONE")][1:], 16)
        source_id = legacy.get("source", 255)
        classification = "ADAPTER_EQUIVALENT" if i < len(old) else "NEW_SOURCE_NO_DIESOUND"
        asset = None
        if i >= len(old) and i in normal["roster_indices"]:
            if cfg["family"] != "bor-original":
                raise SystemExit("FAIL: new foreign model cannot inherit Normal audio")
            pak = ROOT / cfg["pak"]
            identity = cfg["source_character"].split("\\CHARS\\", 1)[1]
            path = cfg.get("source_definition") or source_entry(pak, identity)
            entity = parse_entity(extract(pak, path).decode("latin1"))
            if entity.get("diesound"):
                sound = entity["diesound"].replace("/", "\\").upper()
                asset = cfg["family"] + ":" + (sound if sound.startswith("DATA\\") else "DATA\\" + sound)
                if asset not in known_streams or known_streams[asset] not in known_semantics:
                    raise SystemExit(f"FAIL: new Normal diesound has no source backend: {asset}")
                source_id = known_streams[asset]
                semantic = known_semantics[source_id]
                classification = "NEW_SOURCE_BOUND"
        rows.append({"roster_index": i, "semantic": semantic, "source_id": source_id,
                     "asset": asset, "classification": classification})
    return {"normal_scope": normal, "rows": rows}


def render(data: dict) -> str:
    rows = data["rows"]
    return "\n".join([
        "; GENERATED by tools/audio/generate_normal_audio.py. Normal campaign3 only.",
        "; S7 entries preserve their actual old dispatch, including >=21 exclusions.",
        f"AUDIO_NORMAL_ROSTER_COUNT = {len(rows)}",
        "AudioNormal_DiesoundByRoster:",
        "    .db " + ", ".join(f"${r['semantic']:02X}" for r in rows),
        "AudioNormal_DiesoundSourceByRoster:",
        "    .db " + ", ".join(f"${r['source_id']:02X}" for r in rows), ""])


def main() -> int:
    data = bindings()
    OUTPUT.write_text(render(data), encoding="utf-8")
    (ROOT / "tools/audio/normal_audio_bindings.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"Normal audio: {len(data['rows'])} roster bindings; new source-only dispatch, S7 adapters preserved")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
