#!/usr/bin/env python3
"""Ownership-aware JSR/JSL/JMP/JML target auditor for main.bin.

Extends audit_jumps.py's basic "does this edge land on a real, decodable
instruction" check with a much stronger, fully deterministic one: for every
CALL-class edge (JSR/JSL absolute or long, JMP/JML absolute or long -- the
forms that are supposed to reach a *named* routine, as opposed to a
relative branch's local, sometimes-unlabeled intra-routine target), the
target address must land EXACTLY on some label's address from the current
build's symbol table (`main.sym`, produced by `poppy -s`). If it doesn't,
that's an ownership violation: the compiled bytes are calling into the
*middle* of some other (possibly totally unrelated) label's body rather
than the routine that was actually intended -- which is exactly the class
of bug that broke the abandoned TAD-gap attempt (`jsr Anim_Play` resolving
13 bytes early into the previous routine's live tail code, still decoding
as *valid* instructions the whole way, so audit_jumps.py's own "real
instruction" check couldn't see anything wrong).

Why this catches what audit_jumps.py's basic check can't, and why it's
deterministic (the previous session's abandoned audit_ownership.py sketch
hit non-determinism trying to assign "ownership" of each address via CFG
traversal order -- whichever routine's walk reached an address first "owned"
it, which depended on Python set/stack iteration order and therefore which
call site's m/x state explored a shared routine first):

This version never tries to assign ownership by traversal order at all. It
only asks a single static, order-independent question per CALL edge: does
the numeric target the assembler actually emitted equal *some* label's
real, current address? Labels and their addresses come straight from
`main.sym`, sorted once, independent of any walk order.

IMPORTANT, found by deliberately reproducing a known bug (see Limitation 1
below): this only catches a target that disagrees with EVERY label's
recorded address. It does NOT catch -- and cannot catch, by construction --
a target that agrees with a label's address when that address is itself
wrong. That second case is this project's actual dominant bug class (the
`Anim_Play`-off-by-one bug this tool was tested against, and bug #8's
`AnimRalfWalkFrames`/`AnimRalfAttackFrames` label collisions, are both this
class), so treat a clean run from this tool as a weaker signal than its
name suggests -- see Limitation 1.

Usage:
    python audit_ownership.py <main.bin> <main.sym> <entry_addr_hex> [...]
Example (this project's real entry points):
    python audit_ownership.py src/main.bin src/main.sym FC00 FF00 FF10 8000

NOTE: main.sym mixes real ROM-resident labels (code and data, address
range $8000-$FFFF for this project's single bank $00) together with
constants/equates (small values) and WRAM addresses (bank $7E, i.e.
numerically > $FFFF as this tool parses them) in one flat "bank:addr name"
list. Only entries in [$8000, $FFFF] are ROM-resident labels; those are
the only ones that matter as call-target boundaries, so everything else is
filtered out.

KNOWN LIMITATIONS -- read before trusting a "0 violations" result:

1. CONFIRMED BLIND SPOT, reproduced deliberately, not just theorized: this
   tool trusts main.sym's addresses as ground truth for where labels live,
   but main.sym is generated by the same Poppy estimator that has the
   label-resolves-early bug in the first place, so sym and the emitted
   bytes can (and do) drift TOGETHER, in lockstep, to the same wrong value.
   Reproduced by temporarily deleting the `nop` immediately before
   `Anim_Play:` in main.pasm (its comment already documented that without
   it, `JSR Anim_Play` lands 1 byte early on the previous routine's
   trailing RTS) and rebuilding for real: main.sym reported `Anim_Play` at
   $D372; the true first byte of Anim_Play's body (`SEP #$20` = E2 20)
   was actually at $D373; byte $D372 itself was 0x60 (RTS) -- the previous
   routine's tail, exactly as the comment warned. The compiled `JSR`
   operand was $D372, matching main.sym's (wrong) value exactly. Both
   audit_jumps.py AND this tool reported 0 suspicious/violating edges on
   that build -- a real, live, non-hypothetical broken binary that
   silently passes both checkers, because the ownership check as designed
   can only ever compare a CALL target against label addresses, and here
   the target and the (wrong) label address agree. The nop was restored
   and the build reverted to byte-identical with the known-good binary
   immediately after this test (see git history / handoff.md for the
   verification). Bug #8's AnimRalfWalkFrames/AnimRalfAttackFrames label
   collisions are the same class at larger scale. **Net effect: a clean
   run from this tool is much weaker evidence than "0 violations" sounds
   like** -- it rules out one real but comparatively rare failure mode
   (target drifts to no label at all) and says nothing about the
   project's actual dominant failure mode (a label's own address estimate
   is wrong, and everything referencing it -- sym included -- agrees on
   the wrong value). Still corroborate with raw-byte blob/immediate
   scanning and real Mesen behavioral testing for anything new, especially
   near an unlabeled gap or back-to-back-incbin construct.

2. "Lands exactly on a label boundary" is necessary, not sufficient, for
   "reaches the intended routine" -- it does not parse source to confirm
   which symbol name a given JSR was compiled from, only that its target
   is SOME real label's start address. With ~370 ROM-resident labels over
   ~32KB, a coincidental match to the wrong label is possible in principle
   (not observed in practice on this codebase so far). Corroborate with
   real Mesen behavioral testing before trusting a new ROM region on this
   check alone.
"""
import bisect
import re
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from audit_jumps import disassemble, ABS_CALL_OPCODES, LONG_CALL_OPCODES  # noqa: E402

CALL_KIND_BY_OPCODE = {0x20: 'JSR', 0x4C: 'JMP', 0x22: 'JSL', 0x5C: 'JML'}


def load_labels(sym_path, lo=0x8000, hi=0xFFFF):
    """Return sorted list of (addr, [names]) for bank-00 ROM-resident labels."""
    by_addr = {}
    pattern = re.compile(r'([0-9A-Fa-f]{2}):([0-9A-Fa-f]+)\s+(\S+)')
    with open(sym_path, encoding='utf-8-sig') as f:
        for line in f:
            m = pattern.match(line.strip())
            if not m:
                continue
            bank, addr_s, name = m.groups()
            if bank != '00':
                continue
            addr = int(addr_s, 16)
            if lo <= addr <= hi:
                by_addr.setdefault(addr, []).append(name)
    return sorted(by_addr.items())


def find_owner(labels_sorted, addrs, target):
    """Return (owner_addr, owner_names, next_addr_or_None) for `target`."""
    i = bisect.bisect_right(addrs, target) - 1
    if i < 0:
        return None, None, addrs[0] if addrs else None
    owner_addr, owner_names = labels_sorted[i]
    next_addr = addrs[i + 1] if i + 1 < len(addrs) else None
    return owner_addr, owner_names, next_addr


def redo_call_edges(data, base, entries):
    """Re-walk the CFG but tag each CALL-class edge with its raw opcode byte
    (audit_jumps.py's edges list only carries the mnemonic string, which is
    ambiguous between e.g. absolute JMP $xxxx and indirect JMP ($xxxx) --
    see its own note on reused mnemonic names)."""
    real_addrs, edges, unknown = disassemble(data, base, entries)
    call_edges = []
    for src, target, kind in edges:
        off = src - base
        op = data[off]
        if op in ABS_CALL_OPCODES or op in LONG_CALL_OPCODES:
            call_edges.append((src, target, CALL_KIND_BY_OPCODE[op]))
    return real_addrs, call_edges, edges, unknown


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        raise SystemExit(1)
    bin_path, sym_path = sys.argv[1], sys.argv[2]
    entry_addrs = [int(a, 16) for a in sys.argv[3:]]
    data = open(bin_path, 'rb').read()
    base = 0x8000

    labels_sorted = load_labels(sym_path)
    addrs = [a for a, _ in labels_sorted]
    label_by_addr = dict(labels_sorted)

    entries = [(a, 1, 1, False) for a in entry_addrs]
    real_addrs, call_edges, all_edges, unknown = redo_call_edges(data, base, entries)

    print(f'{len(labels_sorted)} ROM-resident labels loaded from {sym_path}')
    print(f'Decoded {len(real_addrs)} real instruction addresses, '
          f'{len(all_edges)} total control-flow edges, {len(call_edges)} CALL-class edges, '
          f'{len(unknown)} unknown opcodes')

    violations = []
    for src, target, kind in call_edges:
        if target in label_by_addr:
            continue
        owner_addr, owner_names, next_addr = find_owner(labels_sorted, addrs, target)
        if owner_addr is None:
            violations.append((src, target, kind, None, None, 'BEFORE first known label'))
            continue
        offset = target - owner_addr
        violations.append((src, target, kind, owner_addr, owner_names, f'{offset} bytes into'))

    print(f'{len(violations)} OWNERSHIP VIOLATIONS '
          f'(CALL target does not land exactly on a known label):')
    for src, target, kind, owner_addr, owner_names, note in violations[:50]:
        src_owner_addr, src_owner_names, _ = find_owner(labels_sorted, addrs, src)
        src_label = src_owner_names[0] if src_owner_names else '?'
        if owner_addr is None:
            print(f'  {kind} at {hex(src)} (in {src_label}) -> {hex(target)}  {note}')
        else:
            print(f'  {kind} at {hex(src)} (in {src_label}) -> {hex(target)}  '
                  f'{note} {"/".join(owner_names)} (starts {hex(owner_addr)})')

    if not violations:
        print('Clean: every CALL-class edge lands exactly on a real label address.')

    if unknown:
        print(f'{len(unknown)} unknown opcodes hit during walk (first 20):')
        for addr, op in unknown[:20]:
            print(f'  {hex(addr)}: {op:02X}')


if __name__ == '__main__':
    main()
